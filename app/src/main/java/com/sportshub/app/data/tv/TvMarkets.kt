    private val byId: Map<String, TvMarket> = all.associateBy { it.id }

    /** Every market's TV homes added up, in thousands. */
    val totalHomes: Int = all.sumOf { it.tvHomes }

    fun byId(id: String?): TvMarket? = id?.let(byId::get)

    /** The market whose city is closest to a point, e.g. the phone's location. */
    fun nearest(lat: Double, lon: Double): TvMarket =
        all.minBy { Geo.miles(lat, lon, it.lat, it.lon) }

    /** Markets in the lower 48, the ones drawn on the map. */
    val mainland: List<TvMarket> = all.filter { it.state != "AK" && it.state != "HI" }

    /** Markets whose name or state matches what the user typed, best matches first. */
    fun search(query: String): List<TvMarket> {
        val q = query.trim().lowercase()
        if (q.isEmpty()) return all.sortedBy { it.label }
        return all
            .filter { q in it.label.lowercase() }
            .sortedWith(compareBy<TvMarket> { !it.name.lowercase().startsWith(q) }.thenByDescending { it.tvHomes })
    }
